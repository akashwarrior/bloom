export function findPattern(id: string) {
  return PATTERNS.find((pattern) => pattern.id === id) ?? null;
}

export type LibraryCandidates = Record<FrameRole, string[]>;

const CANDIDATE_COUNTS: Record<FrameRole, number> = { hero: 6, section: 10, close: 4 };

/**
 * A random slate of patterns per role, drawn once per build, so two similar
 * prompts start from different frames instead of the same best match.
 */
export function drawCandidates(random: () => number = Math.random): LibraryCandidates {
  const draw = (role: FrameRole) => PATTERNS
    .filter((pattern) => pattern.roles.includes(role))
    .map((pattern) => ({ id: pattern.id, key: random() }))
    .sort((a, b) => a.key - b.key)
    .slice(0, CANDIDATE_COUNTS[role])
    .map((entry) => entry.id);
  return { hero: draw("hero"), section: draw("section"), close: draw("close") };
}

export function candidatesForPrompt(candidates: LibraryCandidates) {
  const line = (id: string) => {
    const pattern = findPattern(id)!;
    return `- ${pattern.id}: ${pattern.name}. ${pattern.use} Not for: ${pattern.notFor}`;
  };
  return (Object.keys(candidates) as FrameRole[])
    .map((role) => `#### ${role === "hero" ? "Hero" : role === "section" ? "Sections" : "Close"}\n${candidates[role].map(line).join("\n")}`)
    .join("\n\n");
}

export function patternDetails(pattern: LibraryPattern) {
  return [
    `${pattern.name} (${pattern.id})`,
    `Composition: ${pattern.composition}`,
    pattern.art ? `Art: ${pattern.art}` : null,
    pattern.ui ? `UI: ${pattern.ui}` : null,
    `Type: ${pattern.type}`,
    `Build with: ${pattern.kit}`,
  ].filter(Boolean).join("\n");
}
